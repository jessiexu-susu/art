const gallery = document.querySelector("#gallery-grid");
const projectContent = document.querySelector("#project-content");
const pages = {
  gallery: document.querySelector("#gallery-page"),
  info: document.querySelector("#info-page"),
  contact: document.querySelector("#contact-page"),
};
const navLinks = [...document.querySelectorAll(".nav-link")];
let currentSlide = 0;

function renderGallery() {
  const columns = [
    {
      title: "Artwork",
      projects: projects.filter(
        (project) => !["Curatorial proposal", "Critical research"].includes(project.category),
      ),
    },
    {
      title: "Curatorial Proposal",
      projects: projects.filter((project) => project.category === "Curatorial proposal"),
    },
    {
      title: "Critical Research",
      projects: projects.filter((project) => project.category === "Critical research"),
    },
  ];

  gallery.innerHTML = columns
    .map(
      ({ title, projects: columnProjects }) => `
        <section class="gallery-column" aria-label="${title}">
          <h2>${title}</h2>
          <div class="gallery-column-grid">
            ${columnProjects
              .map((project) => {
                const index = projects.indexOf(project);
                return `
                  <a class="project-card" href="#info/${project.slug}" aria-label="View ${project.title}">
                    <img src="${project.mainImage}" alt="${project.images[0][1]}" ${index < 3 ? 'fetchpriority="high"' : 'loading="lazy"'} />
                    <span class="project-overlay">
                      <em>${project.category}</em>
                      <strong>${project.title}</strong>
                      <span>${project.year || String(index + 1).padStart(2, "0")}</span>
                    </span>
                  </a>
                `;
              })
              .join("")}
          </div>
        </section>
      `,
    )
    .join("");
}

